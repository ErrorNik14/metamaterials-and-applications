function fh = new_figure(P, width_cm, height_cm)
%NEW_FIGURE  White, fixed-size figure with the project's font/line defaults.
%   fh = new_figure(P)                 full slide width (from P.plot)
%   fh = new_figure(P, w_cm, h_cm)     custom size
if nargin < 2, width_cm  = P.plot.fig_width_cm;  end
if nargin < 3, height_cm = P.plot.fig_height_cm; end

fh = figure('Color', 'w', 'Units', 'centimeters', ...
            'Position', [2 2 width_cm height_cm]);
% R2025a+ follows the desktop dark theme; slides need a white background.
if exist('theme', 'file') || exist('theme', 'builtin')
    theme(fh, 'light');
end
% Defaults set on this figure only, so every axes inside inherits them.
set(fh, 'DefaultAxesColor',         'w', ...
        'DefaultAxesFontName',      P.plot.font_name, ...
        'DefaultAxesFontSize',      P.plot.font_size, ...
        'DefaultAxesXColor',        P.plot.c_ink, ...
        'DefaultAxesYColor',        P.plot.c_ink, ...
        'DefaultAxesLineWidth',     0.75, ...
        'DefaultAxesBox',           'off', ...
        'DefaultAxesTickDir',       'out', ...
        'DefaultAxesTitleFontWeight','normal', ...
        'DefaultLineLineWidth',     P.plot.line_width, ...
        'DefaultLineMarkerSize',    P.plot.marker_size, ...
        'DefaultTextFontName',      P.plot.font_name, ...
        'DefaultTextColor',         P.plot.c_ink, ...
        'DefaultLegendBox',         'off');
end
